    public static class UserDatabase {
        public static void updatePassword(String email, String hashedPassword) throws Exception {
            Connection con = javaconnect.connectDB();
            
            String sql = "UPDATE data SET password=? WHERE email=?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, hashedPassword);
            pst.setString(2, email);
            pst.executeUpdate();
            
            pst.close();
            con.close();
        }
    }
