    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String newPass = new String(jPasswordField1.getPassword()).trim();
        String confirmPass = new String(jPasswordField2.getPassword()).trim();

        if (newPass.isEmpty() || confirmPass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Password fields cannot be empty!");
            return;
        }

        if (!newPass.equals(confirmPass)) {
            JOptionPane.showMessageDialog(this, "Passwords do not match!");
            return;
        }

        try {
            String hashedPassword = hashPassword(newPass);
            UserDatabase.updatePassword(jTextField1.getText().trim(), hashedPassword);

            JOptionPane.showMessageDialog(this, "Password reset successfully!");
            new SignIN().setVisible(true);
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Failed to reset password: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         String email = jTextField1.getText().trim();

        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter your email first!");
            return;
        }

        try {
            generatedOTP = String.valueOf((int)(Math.random() * 900000) + 100000);

            String subject = "Your OTP for Password Reset";
            String body = "Your OTP is: " + generatedOTP;

            EmailSender.send(email, subject, body);

            JOptionPane.showMessageDialog(this, "OTP sent to your email!");
            jPanel2.setVisible(true);

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Failed to send OTP: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String enteredOTP = jTextField2.getText().trim();

        if (enteredOTP.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter the OTP first!");
            return;
        }

        if (enteredOTP.equals(generatedOTP)) {
            JOptionPane.showMessageDialog(this, "OTP Verified!");
            jPanel3.setVisible(true);
        } else {
            JOptionPane.showMessageDialog(this, "Invalid OTP!");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

