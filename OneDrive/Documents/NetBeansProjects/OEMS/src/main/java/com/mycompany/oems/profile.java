private void loadProfile() {
        try {
            String sql = "SELECT * FROM data WHERE id = ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, session.userId);

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                jTextField1.setText(rs.getString("fullname"));
                jTextField2.setText(rs.getString("phone"));
                jTextField3.setText(rs.getString("email"));
                jTextField4.setText(rs.getString("password"));
                jTextField5.setText(rs.getString("address"));
                jTextField6.setText(rs.getString("role"));
            }

            jTextField3.setEditable(false); 
            jTextField6.setEditable(false); 

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    } 
   
